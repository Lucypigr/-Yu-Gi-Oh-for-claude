/** 一般欄位的稀有度機率 */
const NORMAL_SLOT: [Rarity, number][] = [
  ['N', 0.72],
  ['R', 0.22],
  ['SR', 0.05],
  ['UR', 0.01],
];
/** 最後一張保證稀有以上 */
const RARE_SLOT: [Rarity, number][] = [
  ['R', 0.7],
  ['SR', 0.23],
  ['UR', 0.07],
];

function rollRarity(table: [Rarity, number][], rng: () => number): Rarity {
  let r = rng();
  for (const [rarity, p] of table) {
    if (r < p) return rarity;
    r -= p;
  }
  return table[table.length - 1][0];
}

/** 開一包，回傳卡號（同一包內可能重複） */
export function openPack(pack: PackDef, rng: () => number = Math.random): number[] {
  const byRarity: Record<Rarity, number[]> = { N: [], R: [], SR: [], UR: [] };
  for (const id of new Set(pack.cards)) byRarity[rarityOf(id)].push(id);
  const pick = (table: [Rarity, number][]) => {
    let rarity = rollRarity(table, rng);
    // 卡包裡沒有這個稀有度時往下找
    const order: Rarity[] = ['UR', 'SR', 'R', 'N'];
    let i = order.indexOf(rarity);
    while (!byRarity[rarity].length) {
      i = (i + 1) % order.length;
      rarity = order[i];
    }
    const list = byRarity[rarity];
    return list[Math.floor(rng() * list.length)];
  };
  const out: number[] = [];
  for (let i = 0; i < pack.size - 1; i++) out.push(pick(NORMAL_SLOT));
  out.push(pick(RARE_SLOT));
  return out;
}

export function getPack(id: string) {
  return PACKS.find((p) => p.id === id);
}
