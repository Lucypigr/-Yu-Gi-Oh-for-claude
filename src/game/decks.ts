// 起始牌組與電腦對手的牌組
import type { DeckList } from '../engine/duel';

type Entry = [id: number, count: number];

function build(main: Entry[], extra: Entry[] = []): DeckList {
  const expand = (list: Entry[]) => list.flatMap(([id, n]) => Array<number>(n).fill(id));
  return { main: expand(main), extra: expand(extra) };
}

export interface StarterDeck {
  id: string;
  name: string;
  desc: string;
  cover: number;
  deck: DeckList;
}

